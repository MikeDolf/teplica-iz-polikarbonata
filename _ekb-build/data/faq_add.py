def _insert(faq, add):
    """Новые вопросы — перед «Как оплатить…», без повторов формулировок."""
    have = {q.strip().lower().replace("ё", "е") for q, _ in faq}
    add = [x for x in add if x[0].strip().lower().replace("ё", "е") not in have]
    i = next((n for n, (q, _) in enumerate(faq) if q.startswith("Как оплатить")), len(faq))
    return faq[:i] + add + faq[i:]


def apply(pages, products):
    by_slug = {p["slug"]: p for p in pages}
    for slug, add in FAQ_PAGE.items():
        by_slug[slug]["faq"] = _insert(by_slug[slug]["faq"], add)
    for key, add in FAQ_PRODUCT.items():
        products[key]["faq_base"] = _insert(products[key]["faq_base"], add)
