"""Текст, уникальный для пары «город + товар».

Зачем. Гео-страница собирается из блока города (общий для всех товаров
этого города) и блока товара (общий для всех городов). При 15 городах и
11 товарах это давало 165 страниц, у которых совпадение по пятиграммам
доходило до 73%. Поисковик такие страницы склеивает и оставляет одну.

Здесь лежит третий слой: два-три предложения, которые есть ровно на одной
странице. Пишутся от местной фактуры — рельеф, почва, застройка, подъезд —
и от того, под что этот материал реально берут именно тут.

Ключ: (город, товар). Оба ключа как в cities.py и products.py.
"""

CP = {}

# Второй слой уникальности: вопрос-ответ, который встречается ровно на одной
# странице и открывает её FAQ. Общие вопросы товара идут следом.
CPF = {}


def note(city, product, text):
    CP[(city, product)] = " ".join(text.split())


def ask(city, product, q, a):
    """Вопросов на пару может быть несколько, они идут первыми в FAQ.

    Сборка падает, если для одной пары дважды задан один и тот же вопрос:
    так уже случилось на 37 страницах, где во второй партии я переписал
    смысл, уже сформулированный в первой, и на странице оказалось два
    почти одинаковых блока подряд."""
    q = " ".join(q.split())
    bucket = CPF.setdefault((city, product), [])
    assert q not in [x[0] for x in bucket], f"повтор вопроса: {city}/{product} — {q}"
    bucket.append((q, " ".join(a.split())))


