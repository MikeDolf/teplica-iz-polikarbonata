    ("Кабачки и тыква",              r'кабачк|тыкв|патиссон'),
    ("Перец и баклажаны",            r'перц[аыу]|перец|баклажан'),
    ("Газон",                        r'газон'),
    ("Теплица и парник",             r'теплиц|парник'),
    ("Высокие грядки и короба",      r'высок\w+ гряд|короб|приподнят\w+ гряд|грядк\w+ высок'),
    ("Тёплые грядки и биотопливо",   r'тепл\w+ гряд|биотоплив'),
    ("Клумбы и вазоны",              r'клумб|цветник|вазон|альпинари|кашпо|балконн'),
