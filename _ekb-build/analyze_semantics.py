    ("Голубика",                     r'голубик'),
    ("Гортензия",                    r'гортензи'),
    ("Хвойные и туи",                r'туя|туи|можжевельн|хвойн'),
    ("Рододендрон, азалия, вереск",  r'рододендрон|азали|вереск|эрик'),
    ("Клубника и земляника",         r'клубник|земляник'),
    ("Малина",                       r'малин'),
    ("Смородина и крыжовник",        r'смородин|крыжовн'),
    ("Жимолость",                    r'жимолост'),
